const DEFAULT_COLOR = {
  name: "Adventurer",
  bg: "bg-zinc-100",
  text: "text-zinc-700",
  border: "border-zinc-200",
  dot: "bg-zinc-400",
  bar: "bg-zinc-600",
  glow: "shadow-zinc-500/10",
};

/**
 * Returns color tokens for a given class/job name
 */
export function getClassColor(className) {
  if (!className || typeof className !== "string") {
    return DEFAULT_COLOR;
  }

  const normalized = className.trim().toLowerCase();

  // Direct match
  if (CLASS_COLOR_CONFIG[normalized]) {
    return CLASS_COLOR_CONFIG[normalized];
  }

  // Partial / Keyword search
  for (const [key, config] of Object.entries(CLASS_COLOR_CONFIG)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return config;
    }
  }

  return DEFAULT_COLOR;
}

/**
 * Clean visual badge component for class/job
 */
export function ClassBadge({ className: jobName, size = "sm" }) {
  if (!jobName) return null;
  const config = getClassColor(jobName);

  const sizeClasses =
    size === "xs"
      ? "px-1.5 py-0.5 text-[10px]"
      : size === "lg"
      ? "px-2.5 py-1 text-xs"
      : "px-2 py-0.5 text-[11px]";

  return (
    <span
      className={`inline-flex items-center gap-1.5 rounded-md font-semibold border transition ${config.bg} ${config.text} ${config.border} ${sizeClasses}`}
    >
      <span className={`size-1.5 rounded-full shrink-0 ${config.dot}`} />
      <span className="truncate">{jobName}</span>
    </span>
  );
}
